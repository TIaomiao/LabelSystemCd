#!/usr/bin/env python3
"""Generate the frontend CMR result types from the canonical JSON Schema."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any, Mapping


ROOT = Path(__file__).resolve().parents[2]
SCHEMA_PATH = ROOT / "contracts" / "cmr" / "result-envelope.schema.json"
OUTPUT_PATH = ROOT / "apps" / "web" / "src" / "shared" / "cmr-result.generated.ts"


def _ts_literal(value: Any) -> str:
    if value is True:
        return "true"
    if value is False:
        return "false"
    if value is None:
        return "null"
    return json.dumps(value, ensure_ascii=False)


def _property_name(name: str) -> str:
    return name if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", name) else json.dumps(name)


def _indent(text: str, spaces: int = 2) -> str:
    prefix = " " * spaces
    return "\n".join(prefix + line if line else line for line in text.splitlines())


def _ts_type(schema: Mapping[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "oneOf" in schema:
        return " | ".join(_ts_type(branch) for branch in schema["oneOf"])
    if "const" in schema:
        return _ts_literal(schema["const"])
    if "enum" in schema:
        return " | ".join(_ts_literal(value) for value in schema["enum"])

    schema_type = schema.get("type")
    if isinstance(schema_type, list):
        return " | ".join(_ts_type({"type": item}) for item in schema_type)
    if schema_type == "string":
        return "string"
    if schema_type in {"number", "integer"}:
        return "number"
    if schema_type == "boolean":
        return "boolean"
    if schema_type == "null":
        return "null"
    if schema_type == "array":
        if schema.get("maxItems") == 0:
            return "[]"
        return f"Array<{_ts_type(schema.get('items', {}))}>"
    if schema_type == "object":
        properties = schema.get("properties", {})
        additional = schema.get("additionalProperties", True)
        if not properties:
            if additional is True:
                return "Record<string, unknown>"
            if isinstance(additional, Mapping):
                return f"Record<string, {_ts_type(additional)}>"
            return "Record<string, never>"
        required = set(schema.get("required", []))
        lines = [
            f"{_property_name(name)}{'?' if name not in required else ''}: {_ts_type(value)};"
            for name, value in properties.items()
        ]
        return "{\n" + _indent("\n".join(lines)) + "\n}"
    return "unknown"


def _render_named_type(name: str, schema: Mapping[str, Any]) -> str:
    if schema.get("type") == "object" and schema.get("properties") and "oneOf" not in schema:
        required = set(schema.get("required", []))
        fields = [
            f"  {_property_name(field)}{'?' if field not in required else ''}: {_ts_type(value)};"
            for field, value in schema["properties"].items()
        ]
        return f"export interface {name} {{\n" + "\n".join(fields) + "\n}"
    return f"export type {name} = {_ts_type(schema)};"


def render_types(schema_bytes: bytes) -> str:
    schema = json.loads(schema_bytes)
    digest = hashlib.sha256(schema_bytes).hexdigest()
    blocks = [
        "// Generated by scripts/cmr/generate_result_types.py.",
        "// Do not edit by hand; edit contracts/cmr/result-envelope.schema.json.",
        f"// schema-sha256: {digest}",
        "",
    ]
    for name, definition in schema["$defs"].items():
        blocks.extend([_render_named_type(name, definition), ""])
    blocks.append(_render_named_type("CmrResultEnvelope", schema))
    blocks.append("")
    return "\n".join(blocks)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    expected = render_types(SCHEMA_PATH.read_bytes())
    if args.check:
        current = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.is_file() else ""
        if current != expected:
            print(
                "generated CMR result types are stale; run "
                "python3 scripts/cmr/generate_result_types.py",
                file=sys.stderr,
            )
            return 1
        return 0

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
